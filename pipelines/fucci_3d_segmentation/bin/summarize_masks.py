#!/usr/bin/env python3
from __future__ import annotations

import argparse
import csv
from pathlib import Path

from _bootstrap import add_src_to_path

add_src_to_path()

from image_datamining.fucci_3d_segmentation.masks import summarize_mask, write_object_summary


def main() -> None:
    parser = argparse.ArgumentParser(description="Summarize pixel-to-object mask TIFFs.")
    parser.add_argument("--command-manifest", type=Path, help="TSV generated by write_cellpose_commands.py.")
    parser.add_argument("--mask", action="append", type=Path, help="Mask TIFF to summarize. May be repeated.")
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()

    rows = []
    if args.command_manifest:
        with args.command_manifest.open(newline="") as handle:
            for command_row in csv.DictReader(handle, delimiter="\t"):
                mask_path = Path(command_row["mask_path"])
                if mask_path.exists():
                    rows.extend(summarize_mask(mask_path, sample_id=command_row["sample_id"]))
    for mask_path in args.mask or []:
        rows.extend(summarize_mask(mask_path, sample_id=mask_path.stem))

    write_object_summary(rows, args.output)
    print(f"wrote {len(rows)} object rows to {args.output}")


if __name__ == "__main__":
    main()

